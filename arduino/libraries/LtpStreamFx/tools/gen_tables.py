#!/usr/bin/env python3
"""Generate src/ltp_fx_tables.h, the flash lookup tables of the LtpStreamFx engine.

Run from anywhere:  python3 tools/gen_tables.py
The output is checked in; rerun only when a table or palette changes.
"""
import math
import random
from pathlib import Path

# The LEDs are driven with linear PWM, so palette colours are gamma-corrected
# here, once, instead of per pixel in the firmware.
GAMMA = 2.2

# Fixed seed so the noise lattice, and with it every noise-based effect, looks
# the same on every build.
PERM_SEED = 20261116

TABLE_SIZE = 256


def gamma8(c):
    return round(255 * (max(0.0, min(255.0, c)) / 255) ** GAMMA)


def gradient(stops):
    """Linear interpolation through (position 0..255, (r, g, b)) stops."""
    out = []
    for i in range(TABLE_SIZE):
        for (p0, c0), (p1, c1) in zip(stops, stops[1:]):
            if p0 <= i <= p1:
                f = 0 if p1 == p0 else (i - p0) / (p1 - p0)
                out.append(tuple(c0[k] + (c1[k] - c0[k]) * f for k in range(3)))
                break
    return out


def rainbow():
    out = []
    for i in range(TABLE_SIZE):
        h = i * 6 / TABLE_SIZE
        f = h - int(h)
        up, down = 255 * f, 255 * (1 - f)
        out.append([(255, up, 0), (down, 255, 0), (0, 255, up),
                    (0, down, 255), (up, 0, 255), (255, 0, down)][int(h)])
    return out


# Order must match the FXPAL_* table palettes in ltp_fx.h (after Default, Color).
PALETTES = [
    ("Rainbow", rainbow()),
    ("Heat", gradient([(0, (0, 0, 0)), (85, (255, 0, 0)),
                       (170, (255, 255, 0)), (255, (255, 255, 255))])),
    ("Ocean", gradient([(0, (0, 0, 40)), (70, (0, 30, 150)), (140, (0, 130, 170)),
                        (205, (60, 220, 200)), (255, (220, 255, 255))])),
    ("Forest", gradient([(0, (0, 40, 0)), (70, (0, 110, 10)), (140, (50, 170, 20)),
                         (200, (150, 210, 40)), (255, (30, 90, 0))])),
    ("Lava", gradient([(0, (0, 0, 0)), (50, (90, 0, 0)), (110, (200, 0, 0)),
                       (165, (255, 70, 0)), (215, (255, 170, 0)),
                       (255, (255, 255, 130))])),
    # Cyclic: the last stop equals the first, so scrolling it has no seam.
    ("Party", gradient([(0, (110, 0, 200)), (51, (220, 0, 120)), (102, (255, 20, 0)),
                        (153, (255, 130, 0)), (204, (240, 220, 0)),
                        (230, (255, 60, 40)), (255, (110, 0, 200))])),
    ("Ice", gradient([(0, (0, 0, 0)), (80, (0, 20, 130)), (160, (0, 140, 230)),
                      (215, (120, 220, 255)), (255, (255, 255, 255))])),
]


def c_array(name, values, per_line=16):
    lines = [f"static const uint8_t {name}[{len(values)}] FX_PROGMEM = {{"]
    for i in range(0, len(values), per_line):
        lines.append("    " + ",".join(f"{v:3d}" for v in values[i:i + per_line]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    sin8 = [round(127.5 + 127.5 * math.sin(2 * math.pi * i / TABLE_SIZE))
            for i in range(TABLE_SIZE)]
    # Smoothstep 3t^2 - 2t^3: removes the creases linear interpolation leaves
    # at the noise lattice points.
    ease8 = [round(255 * (3 * (i / 255) ** 2 - 2 * (i / 255) ** 3))
             for i in range(TABLE_SIZE)]
    perm8 = list(range(TABLE_SIZE))
    random.Random(PERM_SEED).shuffle(perm8)

    parts = [
        "// Generated by tools/gen_tables.py - do not edit by hand.",
        "#ifndef LTP_FX_TABLES_H",
        "#define LTP_FX_TABLES_H",
        "",
        f"// Palettes are gamma-corrected (gamma {GAMMA}) RGB triplets, 256 entries each.",
        f"#define FX_TABLE_PALETTES {len(PALETTES)}",
        "",
        "// 127.5 + 127.5 * sin(2 * pi * i / 256)",
        c_array("fxSinTable", sin8),
        "",
        "// Smoothstep, used to interpolate the noise lattice.",
        c_array("fxEaseTable", ease8),
        "",
        "// Permutation of 0..255: the hash behind noise, sparkle and twinkle.",
        c_array("fxPermTable", perm8),
        "",
    ]
    flat = []
    for name, colours in PALETTES:
        assert len(colours) == TABLE_SIZE, name
        for rgb in colours:
            flat.extend(gamma8(c) for c in rgb)
    names = ", ".join(name for name, _ in PALETTES)
    parts += [f"// Table palettes in FXPAL_* order: {names}.",
              c_array("fxPaletteTable", flat, per_line=12), "",
              "#endif // LTP_FX_TABLES_H", ""]

    out = Path(__file__).resolve().parent.parent / "src" / "ltp_fx_tables.h"
    out.write_text("\n".join(parts))
    print(f"wrote {out} ({len(flat) + 3 * TABLE_SIZE} table bytes)")


if __name__ == "__main__":
    main()
