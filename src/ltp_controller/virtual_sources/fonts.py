DEFAULT_FONT = "5x7"


def get_font(name: str) -> tuple[FontInfo, dict[str, list[int]]]:
    """Get font info and data by name."""
    if name not in FONTS:
        raise ValueError(f"Unknown font: {name}. Available: {list(FONTS.keys())}")
    return FONTS[name]


def list_fonts() -> list[str]:
    """List available font names."""
    return list(FONTS.keys())


def get_char_bitmap(char: str, font_name: str = DEFAULT_FONT) -> list[int] | None:
    """Get bitmap data for a character.

    Returns:
        List of row bytes, or None if character not in font.
    """
    info, data = get_font(font_name)

    # Try exact match
    if char in data:
        return data[char]

    # Try uppercase
    if char.upper() in data:
        return data[char.upper()]

    # Return space for unknown characters
    return data.get(" ")
